#!/usr/bin/env python3
"""Rebuild the generated Apps Script files. Run after changing anything in this folder:

    python3 build.py

- MatrixSchemas.gs  <- matrix/*.js (the OneKey Matrix input sheets, shared with the
                       standalone matrix-listing-intake app)
- DealTracker.gs    <- Code.gs + Matrix.gs + ListingChanges.gs + MatrixSchemas.gs + Index.html, as one file
                       for the single-paste setup
"""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
SCHEMA_FILES = ["residential.js", "derive.js", "coop-condo.js", "multi-2-4.js", "rental.js", "land.js"]


def read(name):
    with open(os.path.join(HERE, name), encoding="utf-8") as f:
        return f.read()


def write(name, text):
    with open(os.path.join(HERE, name), "w", encoding="utf-8") as f:
        f.write(text)


def build_schemas():
    parts = [
        "/**\n"
        " * GENERATED by build.py from matrix/*.js. Do not edit here; edit matrix/*.js and run build.py.\n"
        " * OneKey MLS Matrix input sheets, one schema per property type.\n"
        " */\n"
        "// The schema files were written for the browser; on the server they attach to this object instead.\n"
        "var window = (typeof window !== 'undefined') ? window : {};\n"
    ]
    for name in SCHEMA_FILES:
        parts.append(f"\n// ---- matrix/{name}\n" + read(os.path.join("matrix", name)))
    parts.append("\nfunction MATRIX_SCHEMAS_() { return window.SCHEMAS; }\n")
    return "".join(parts)


def main():
    schemas = build_schemas()
    write("MatrixSchemas.gs", schemas)
    code = read("Code.gs").rstrip("\n")
    matrix = read("Matrix.gs").rstrip("\n")
    changes = read("ListingChanges.gs").rstrip("\n")
    page = read("Index.html")
    bundle = (
        code + "\n\n"
        "// ---------------------------------------------------------------------------\n"
        "// MLS LISTING (Matrix.gs)\n"
        "// ---------------------------------------------------------------------------\n"
        + matrix + "\n\n"
        "// ---------------------------------------------------------------------------\n"
        "// LISTING CHANGES (ListingChanges.gs)\n"
        "// ---------------------------------------------------------------------------\n"
        + changes + "\n\n"
        "// ---------------------------------------------------------------------------\n"
        "// MATRIX INPUT SHEETS (MatrixSchemas.gs)\n"
        "// ---------------------------------------------------------------------------\n"
        + schemas.rstrip("\n") + "\n\n"
        "// ---------------------------------------------------------------------------\n"
        "// THE PAGE AGENTS SEE (kept in this file so the whole app is one paste)\n"
        "// ---------------------------------------------------------------------------\n"
        "var INDEX_HTML = " + json.dumps(page) + ";\n"
    )
    write("DealTracker.gs", bundle)
    print("Built MatrixSchemas.gs (%d lines) and DealTracker.gs (%d lines)" % (schemas.count("\n"), bundle.count("\n")))


if __name__ == "__main__":
    main()
